# PrintPay Windows Desktop Agent
# Requires: Python 3.10+ on the shop computer.
# Set BASE_URL and DESKTOP_KEY below, then run: python desktop_agent.py
import os,time,requests,tempfile,subprocess
BASE_URL=os.environ.get('PRINTPAY_URL','https://YOUR-PRINTPAY-URL')
DESKTOP_KEY=os.environ.get('PRINTPAY_DESKTOP_KEY','CHANGE-ME-PRINTPAY')
seen=set()

def print_file(path):
    # Windows: sends the file to the default printer using the file's registered Print verb.
    os.startfile(path,'print')

def main():
    print('PrintPay Desktop Agent started. Keep this window running.')
    while True:
        try:
            r=requests.get(BASE_URL.rstrip('/')+'/api/desktop/jobs',headers={'x-desktop-key':DESKTOP_KEY},timeout=30)
            r.raise_for_status(); jobs=r.json().get('jobs',[])
            for j in jobs:
                # Print only the final PDF generated by the customer; avoid duplicate source files.
                if j['id'] in seen or j['file_name'] != 'FINAL-PRINT.pdf': continue
                fr=requests.get(BASE_URL.rstrip('/')+'/api/desktop/file?key='+requests.utils.quote(j['file_key'],safe=''),headers={'x-desktop-key':DESKTOP_KEY},timeout=60)
                fr.raise_for_status()
                fd,path=tempfile.mkstemp(prefix='PrintPay-',suffix='.pdf');os.close(fd)
                open(path,'wb').write(fr.content)
                for _ in range(max(1,int(j.get('copies') or 1))):
                    print_file(path)
                    time.sleep(2)
                seen.add(j['id'])
                requests.post(BASE_URL.rstrip('/')+'/api/desktop/printed',headers={'x-desktop-key':DESKTOP_KEY,'content-type':'application/json'},json={'order_id':j['id']},timeout=30)
                time.sleep(3)
        except Exception as e:
            print('Agent:',e)
        time.sleep(3)
if __name__=='__main__': main()
